"""
Draft explanations built only from what is already stored: the question, its
passage and its answer key. Nothing is generated by a model and nothing is
invented — a question gets a draft only when a sentence of its own passage
backs the key. Drafts are saved with ``explanation_status="draft"`` so students
see an "AI-prepared" label until staff approve them.

Listening questions have no transcript, so they never get a draft.
"""

from __future__ import annotations

import re

from .question_review import source_text_for
from .scoring import normalize_text

_STOP = set(
    "the a an and or of to in on at for with by from is are was were be been it its this that these those as "
    "which what who whom whose when where why how do does did has have had not no yes about into than then "
    "their there they them he she his her you your we our i my me".split()
)
_TEMPLATES = {
    "uz": "To'g'ri javob: {answer}.",
    "ru": "Правильный ответ: {answer}.",
    "en": "Correct answer: {answer}.",
}


def split_sentences(text: str) -> list[str]:
    parts = re.split(r"(?<=[.!?])\s+|\n+", text or "")
    return [p.strip() for p in parts if len(p.strip()) > 15]


def _content_words(text: str) -> set[str]:
    return {w for w in re.findall(r"[a-z0-9']+", normalize_text(text)) if len(w) > 2 and w not in _STOP}


def _has_phrase(sentence: str, phrase: str) -> bool:
    return bool(re.search(r"(?<![\w'])" + re.escape(normalize_text(phrase)) + r"(?![\w'])", normalize_text(sentence)))


def correct_texts(question) -> list[str]:
    keys = [k.strip() for k in (question.correct_text or "").split("|") if k.strip()]
    if not keys:
        keys = [b.answer_text.strip() for b in question.gap_blanks.all() if (b.answer_text or "").strip()]
    if not keys:
        keys = [c.text.strip() for c in question.choices.all() if c.is_correct and c.text.strip()]
    return keys


def find_evidence(question, answers: list[str], passage: str) -> str:
    """The passage sentence that best backs the key, or '' when none does."""
    sentences = split_sentences(passage)
    if not sentences or not answers:
        return ""
    query = _content_words(question.text)
    is_gap = question.question_type in ("INLINE_GAP_FILL", "SHORT_ANSWER", "text", "gap_fill")

    if is_gap:
        # Cloze passage: the sentence holding this question's numbered gap,
        # shown with the key filled in.
        number = (question.config or {}).get("number")
        if number is not None:
            gap = re.compile(rf"\(\s*{int(number)}\s*\)\s*_+")
            for s in sentences:
                found = gap.search(s)
                if found:
                    filled = gap.sub(answers[0], s)
                    return filled[:1].upper() + filled[1:] if found.start() == 0 else filled
        # Otherwise the answer itself must occur in the passage.
        scored = [
            (len(query & _content_words(s)), s)
            for s in sentences
            if any(_has_phrase(s, a) for a in answers)
        ]
        if scored:
            return max(scored, key=lambda x: x[0])[1]
        return ""

    # Choice / true-false / matching: overlap with the statement and the correct option.
    query |= _content_words(" ".join(answers)) if question.question_type != "TRUE_FALSE_NOT_GIVEN" else set()
    best, best_score = "", 0
    for s in sentences:
        score = len(query & _content_words(s))
        if score > best_score:
            best, best_score = s, score
    return best if best_score >= 3 else ""


def draft_for(question, lang: str = "uz") -> tuple[str, str] | None:
    """(explanation, evidence) for a question, or None when nothing may be said."""
    section = getattr(question, "section", None)
    if (getattr(section, "code", "") or "").upper() in ("LISTENING", "SPEAKING", "WRITING"):
        return None
    if question.question_type in ("written", "SPEAKING_PROMPT"):
        return None
    answers = correct_texts(question)
    if not answers:
        return None
    evidence = find_evidence(question, answers, source_text_for(question))
    if not evidence:
        return None
    shown = " / ".join(a.rstrip(".") for a in answers[:2])
    return _TEMPLATES.get(lang, _TEMPLATES["uz"]).format(answer=shown), evidence
